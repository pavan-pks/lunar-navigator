#!/usr/bin/env python3
"""
scripts/make_fake_data.py
Generates plausible synthetic lunar ephemeris for Day-0 offline prototyping.
Output: public/data/global_ephem.json
"""

import json
import math
import os
from datetime import datetime, timezone, timedelta

def generate_fake_ephem(
    start_utc_str="2027-01-01T00:00:00Z",
    stop_utc_str="2028-01-31T23:00:00Z",
    step_hours=1,
    output_path="public/data/global_ephem.json"
):
    start_dt = datetime.fromisoformat(start_utc_str.replace("Z", "+00:00"))
    stop_dt = datetime.fromisoformat(stop_utc_str.replace("Z", "+00:00"))

    total_hours = int((stop_dt - start_dt).total_seconds() // 3600) + 1

    # Astronomical constants for plausible simulation
    synodic_hours = 29.530589 * 24.0      # ~708.734 hours (synodic month)
    tropical_year_hours = 365.2422 * 24.0  # Seasonal solar latitude cycle
    anomalistic_hours = 27.55455 * 24.0   # Optical libration in longitude
    draconic_hours = 27.21222 * 24.0      # Optical libration in latitude

    sub_solar_lat = []
    sub_solar_lon = []
    sub_earth_lat = []
    sub_earth_lon = []

    # Initial sun longitude offset on Jan 1 2027
    lon0 = 75.0

    for step in range(total_hours):
        t = float(step * step_hours)

        # 1. Sub-solar longitude (drifts westward ~360 deg per synodic month)
        # Longitude convention: East is positive (-180 to +180)
        raw_solar_lon = lon0 - (360.0 * t / synodic_hours)
        solar_lon = ((raw_solar_lon + 180.0) % 360.0) - 180.0

        # 2. Sub-solar latitude (~1.54 deg seasonal tilt to ecliptic)
        solar_lat = 1.54 * math.sin((2.0 * math.pi * t) / tropical_year_hours)

        # 3. Sub-Earth libration longitude (~6.5 deg amplitude, ~27.55d period)
        earth_lon = 6.5 * math.sin((2.0 * math.pi * t) / anomalistic_hours)

        # 4. Sub-Earth libration latitude (~6.7 deg amplitude, ~27.21d period)
        earth_lat = 6.7 * math.sin((2.0 * math.pi * t) / draconic_hours)

        sub_solar_lat.append(round(solar_lat, 3))
        sub_solar_lon.append(round(solar_lon, 3))
        sub_earth_lat.append(round(earth_lat, 3))
        sub_earth_lon.append(round(earth_lon, 3))

    data = {
        "fake": True,
        "source": "Synthetic lunar ephemeris generated by scripts/make_fake_data.py for offline prototyping",
        "startUTC": start_utc_str,
        "stepHours": step_hours,
        "count": len(sub_solar_lat),
        "subSolarLat": sub_solar_lat,
        "subSolarLon": sub_solar_lon,
        "subEarthLat": sub_earth_lat,
        "subEarthLon": sub_earth_lon,
    }

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, separators=(",", ":"))

    print(f"Generated fake ephemeris: {len(sub_solar_lat)} steps written to {output_path}")

if __name__ == "__main__":
    generate_fake_ephem()
